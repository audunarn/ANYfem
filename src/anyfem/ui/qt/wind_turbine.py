        self.mass_mode.addItem('Already modelled / no additional mass', 'already_modelled')
        self.mass_mode.addItem('Add to structural mass model', 'additional')
        form.addRow('Mass ownership', self.mass_mode)
        edit('mass', 'Turbine mass (kg)')
        edit('mass_cg', 'Mass CG offset from attachment (body x y z, m)')
        edit('inertia', 'Inertia at CG (Ixx Iyy Izz Ixy Ixz Iyz, kg m²)')
        self.mass_mode.currentIndexChanged.connect(lambda *_: self._sync_enabled())
        self.rotor_mode = QComboBox(); self.rotor_mode.setObjectName('wt_rotor_mode')
        self.rotor_mode.addItem('Yaw / tilt (deg)', 'yaw_tilt'); self.rotor_mode.addItem('Unit rotor axis (body)', 'axis')
        form.addRow('Rotor orientation', self.rotor_mode)
        edit('yaw', 'Rotor yaw (deg)'); edit('tilt', 'Rotor tilt (deg)')
