"""Wind turbine load editor (Loads & BC): create, edit, list and delete saved reusable turbine load definitions.

Each definition is one immutable ``WindTurbineLoad`` in ``Project.wind_turbine_loads``: thrust curve, ABSOLUTE body hub
point and structural hub node, rotor yaw/tilt or unit axis, and the wind it owns - a steady declared mean, imported
3-component samples (the CSV is read once at Save and its SAMPLES are stored in the project), or a longitudinal Kaimal
realization generated by ANYloads whose coefficients are retained (an edit that keeps the Kaimal parameters keeps the
realization exactly).  Every change is one undoable command through ``app.run``.  Nothing here runs BEM, a mean solve
or solves dynamics. Explicit additional mass enters every structural build; floating transient runs select thrust by name.
"""
from __future__ import annotations

from pathlib import Path

import numpy as np
from PySide6.QtCore import Qt
from PySide6.QtWidgets import (QComboBox, QDialog, QFormLayout, QHBoxLayout, QLabel, QLineEdit, QListWidget,
                               QListWidgetItem, QPushButton, QVBoxLayout, QScrollArea, QWidget)

from ...commands import AddWindTurbineLoad, DeleteWindTurbineLoad, EditWindTurbineLoad
from ...model.wind_turbine import WindTurbineLoad
from .floating_transient import parse_curve, parse_vector

DEFAULTS = dict(name='Turbine', thrust_curve='0:0, 10:1000, 20:1500', hub='0 0 10', hub_node='', yaw='0', tilt='0',
                axis='1 0 0', wind_mean='10 0 0', import_file='', ti='0.1', length='340.2', seed='1', dt='0.1',
                duration='600', fmax='', attachment_element='', mass='0', mass_cg='0 0 0', inertia='0 0 0 0 0 0')


def _number(value):
    return repr(float(value))


class WindTurbineLoadEditor(QDialog):
    def __init__(self, panel, parent=None):
        super().__init__(parent if parent is not None else panel)
        self.panel, self.app = panel, panel.app
        self.editing_id = None
        self.setWindowTitle('Wind turbine loads'); self.setObjectName('WindTurbineLoadEditor')
        layout = QVBoxLayout(self)
        layout.addWidget(QLabel('Saved wind turbine loads (dynamic loads used only by floating transient runs; '
                                'explicit additional mass is included in every structural analysis)'))
        self.list = QListWidget(); self.list.setObjectName('wt_list'); self.list.setMaximumHeight(140)
        self.list.currentItemChanged.connect(lambda current, _previous: self._list_selected(current))
        layout.addWidget(self.list)
        scroll = QScrollArea(); scroll.setWidgetResizable(True)
        form_widget = QWidget(); form = QFormLayout(form_widget); scroll.setWidget(form_widget)
        form.setRowWrapPolicy(QFormLayout.RowWrapPolicy.WrapLongRows)
        layout.addWidget(scroll); self.resize(900, 850)
        self.fields = {}

        def edit(key, label):
            w = QLineEdit(DEFAULTS[key]); w.setObjectName('wt_' + key); self.fields[key] = w; form.addRow(label, w)
            return w

        edit('name', 'Name')
        edit('thrust_curve', 'Thrust curve (rotor-axial speed : thrust, ...)')
        edit('hub', 'Hub position / offset (body x y z, m)')
        edit('hub_node', 'Attachment structural node id (e.g. tower top)')
        edit('attachment_element', 'Attachment element id (optional membership check)')
        self.hub_reference = QComboBox()
        self.hub_reference.addItem('Absolute body coordinates', 'absolute')
        self.hub_reference.addItem('Offset from attachment node', 'attachment')
