    # ---------------------------------------------------------------- list
    def records(self):
        return sorted((getattr(self.app.project, 'wind_turbine_loads', {}) or {}).values(), key=lambda r: r.name)

    def refresh(self, select=None):
        self.list.blockSignals(True)
        try:
            self.list.clear()
            for record in self.records():
                item = QListWidgetItem(f'{record.name} - {record.wind_mode} wind, hub node {record.hub_node_id}')
                item.setData(Qt.UserRole, record.id)
                self.list.addItem(item)
                if record.id == select:
                    self.list.setCurrentItem(item)
        finally:
            self.list.blockSignals(False)
        if select is not None and select in (self.app.project.wind_turbine_loads or {}):
            self.load_record(self.app.project.wind_turbine_loads[select])

    def _list_selected(self, item):
        if item is None:
            return
        record = self.app.project.wind_turbine_loads.get(item.data(Qt.UserRole))
        if record is not None:
            self.load_record(record)

    def select(self, key):
        """Select a saved turbine load by name or ID for editing."""
        record = self.app.project.wind_turbine_load(key)
        self.refresh(select=record.id)
        return record

    # ---------------------------------------------------------------- fields
    def _sync_enabled(self):
        axis = self.rotor_mode.currentData() == 'axis'
        self.fields['axis'].setEnabled(axis)
        self.fields['yaw'].setEnabled(not axis); self.fields['tilt'].setEnabled(not axis)
        for key in ('mass', 'mass_cg', 'inertia'):
            self.fields[key].setEnabled(self.mass_mode.currentData() == 'additional')
        mode = self.wind_mode.currentData()
        self.fields['import_file'].setEnabled(mode == 'import')
        for key in ('ti', 'length', 'seed', 'dt', 'duration', 'fmax'):
            self.fields[key].setEnabled(mode == 'kaimal')

    def new(self):
        self.editing_id = None
        self.hub_reference.setCurrentIndex(0); self.mass_mode.setCurrentIndex(0)
        self.list.blockSignals(True); self.list.setCurrentRow(-1); self.list.clearSelection(); self.list.blockSignals(False)
        for key, value in DEFAULTS.items():
            self.fields[key].setText(value)
        self.rotor_mode.setCurrentIndex(0); self.wind_mode.setCurrentIndex(0)
        self.summary.setText(''); self.status.setText('New turbine load: fill in the fields and Save.')

    def load_record(self, record):
        self.editing_id = record.id
        f = self.fields
        f['name'].setText(record.name)
        f['thrust_curve'].setText(', '.join(f'{_number(v)}:{_number(t)}'
                                            for v, t in zip(record.thrust_speeds, record.thrust_values)))
        f['hub'].setText(' '.join(_number(x) for x in record.hub_body))
        f['hub_node'].setText(str(record.hub_node_id))
        f['attachment_element'].setText('' if record.attachment_element_id is None else str(record.attachment_element_id))
        self.hub_reference.setCurrentIndex(self.hub_reference.findData(record.hub_reference))
        self.mass_mode.setCurrentIndex(self.mass_mode.findData(record.mass_mode))
        f['mass'].setText(_number(record.mass))
        f['mass_cg'].setText(' '.join(_number(x) for x in record.mass_cg_offset))
        J = record.inertia_cg
        f['inertia'].setText(' '.join(_number(x) for x in (J[0][0],J[1][1],J[2][2],J[0][1],J[0][2],J[1][2])))
        if record.rotor_axis is None:
            self.rotor_mode.setCurrentIndex(self.rotor_mode.findData('yaw_tilt'))
            f['yaw'].setText(_number(record.rotor_yaw_deg)); f['tilt'].setText(_number(record.rotor_tilt_deg))
        else:
            self.rotor_mode.setCurrentIndex(self.rotor_mode.findData('axis'))
            f['axis'].setText(' '.join(_number(x) for x in record.rotor_axis))
        self.wind_mode.setCurrentIndex(self.wind_mode.findData(record.wind_mode))
        f['wind_mean'].setText(' '.join(_number(x) for x in record.reference_mean_world))
        f['import_file'].setText('')
        if record.wind_mode == 'kaimal':
            f['ti'].setText(_number(record.turbulence_intensity)); f['length'].setText(_number(record.integral_scale))
            f['seed'].setText(str(record.seed)); f['dt'].setText(_number(record.timestep))
            f['duration'].setText(_number(record.duration)); f['fmax'].setText(_number(record.max_frequency))
        self.summary.setText(self.describe(record))
        self.status.setText(f'Editing {record.name!r}; Save applies one undoable edit.')

    @staticmethod
    def describe(record):
        text = (f'{record.name}: hub {list(record.hub_body)} ({record.hub_reference} body coordinates) on node {record.hub_node_id}; '
                f'declared mean {list(record.reference_mean_world)} m/s; ')
        if record.wind_mode == 'import':
            return text + (f'{len(record.import_times)} imported samples over [{record.import_times[0]:.6g}, '
                           f'{record.import_times[-1]:.6g}] s (stored in the project)')
        if record.wind_mode == 'kaimal':
            real = record.kaimal_realization()
            return text + (f'retained Kaimal realization: {real.frequencies.size} components over [0, '
                           f'{record.duration:.6g}] s, seed {record.seed}; represented variance '
                           f'{real.represented_variance:.6g} of {real.target_variance:.6g} (m/s)^2, omitted low '
                           f'{real.missing_low_variance:.6g}, omitted high {real.missing_high_variance:.6g}')
        return text + 'steady wind'

    def record_from_fields(self, previous=None):
        """A validated record from the fields; an unchanged Kaimal parameter set keeps ``previous``'s realization."""
        f = {k: w.text().strip() for k, w in self.fields.items()}
        speeds, thrusts = parse_curve(f['thrust_curve'])
        if not f['hub_node']:
            raise ValueError('choose the structural hub node id')
        if self.rotor_mode.currentData() == 'axis':
            rotor = dict(rotor_axis=parse_vector(f['axis'], 'rotor axis'))
        else:
            rotor = dict(rotor_yaw_deg=float(f['yaw']), rotor_tilt_deg=float(f['tilt']))
        mode = self.wind_mode.currentData()
        wind = {}
        if mode == 'import':
            if f['import_file']:
                data = np.loadtxt(f['import_file'], delimiter=',', ndmin=2)
                if data.ndim != 2 or data.shape[1] != 4:
                    raise ValueError('imported wind must be a CSV "t,u,v,w"')
                wind = dict(import_times=data[:, 0], import_velocity=data[:, 1:],
                            import_source=Path(f['import_file']).name)
            elif previous is not None and previous.wind_mode == 'import':
                wind = dict(import_times=previous.import_times, import_velocity=previous.import_velocity,
                            import_source=previous.import_source)
            else:
                raise ValueError('choose the CSV to import (its samples are stored in the project)')
        elif mode == 'kaimal':
            wind = dict(turbulence_intensity=float(f['ti']), integral_scale=float(f['length']), seed=int(f['seed']),
                        timestep=float(f['dt']), duration=float(f['duration']),
                        max_frequency=float(f['fmax']) if f['fmax'] else None)
        inertia = [float(x) for x in f['inertia'].replace(',', ' ').split()]
        if len(inertia) != 6:
            raise ValueError('inertia needs Ixx Iyy Izz Ixy Ixz Iyz (actual tensor entries)')
        xx, yy, zz, xy, xz, yz = inertia
        return WindTurbineLoad.create(f['name'], thrust_speeds=speeds, thrust_values=thrusts,
                                      hub_body=parse_vector(f['hub'], 'hub position'), hub_node_id=int(f['hub_node']),
                                      wind_mode=mode,
                                      reference_mean_world=parse_vector(f['wind_mean'], 'reference mean wind'),
                                      previous=previous, **rotor, **wind,
                                      attachment_element_id=int(f['attachment_element']) if f['attachment_element'] else None,
                                      hub_reference=self.hub_reference.currentData(), mass_mode=self.mass_mode.currentData(),
                                      mass=float(f['mass']), mass_cg_offset=parse_vector(f['mass_cg'], 'mass CG offset'),
                                      inertia_cg=((xx,xy,xz),(xy,yy,yz),(xz,yz,zz)))

    # ---------------------------------------------------------------- commands
    def _writable(self):
        if getattr(getattr(self.app, 'session', None), 'read_only', False):
            raise ValueError('the project is read-only')

    def save(self):
        """Create (no record selected) or edit the selected record: one undoable command."""
        try:
            self._writable()
            previous = self.app.project.wind_turbine_loads.get(self.editing_id) if self.editing_id else None
            if self.editing_id and previous is None:
                raise ValueError('the edited turbine load no longer exists; choose New')
            record = self.record_from_fields(previous)
            if previous is not None and record == previous:
                self.status.setText(f'{record.name!r} unchanged; nothing applied')
                return previous
            result = self.app.run(AddWindTurbineLoad(record) if previous is None else EditWindTurbineLoad(record))
            self.refresh(select=result.id)
            self.status.setText(('Created ' if previous is None else 'Updated ') + f'{result.name!r}; Undo reverts it')
            return result
        except Exception as error:  # noqa: BLE001 - any refusal is reported, nothing is applied
            self.status.setText('Refused: ' + str(error))
            return None

    def delete(self):
        try:
            self._writable()
            if not self.editing_id:
                raise ValueError('select a turbine load to delete')
            removed = self.app.run(DeleteWindTurbineLoad(self.editing_id))
            self.refresh(); self.new()
            self.status.setText(f'Deleted {removed.name!r}; Undo restores it')
            return removed
        except Exception as error:  # noqa: BLE001
            self.status.setText('Refused: ' + str(error))
            return None
