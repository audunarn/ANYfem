        form.addRow('Wind', self.wind_mode)
        edit('wind_mean', 'Declared reference mean wind, world (u v w, m/s)')
        edit('import_file', 'Import CSV (blank = keep the stored samples)')
        edit('ti', 'Turbulence intensity (Kaimal)')
        edit('length', 'Integral length scale L (m, Kaimal)')
        edit('seed', 'Seed (Kaimal)')
